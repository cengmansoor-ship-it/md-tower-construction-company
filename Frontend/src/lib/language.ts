const orderedTranslations = Object.entries(translations).sort((left, right) => right[0].length - left[0].length);
const textOriginals = new WeakMap<Text, string>();
const attrOriginals = new WeakMap<Element, Record<string, string>>();
let activeObserver: MutationObserver | null = null;

function translateValue(value: string, language: AppLanguage): string {
  if (language === "ps") return value;
  const leading = value.match(/^\s*/)?.[0] ?? "";
  const trailing = value.match(/\s*$/)?.[0] ?? "";
  const core = value.trim();
  if (!core) return value;
  const exact = translations[core];
  if (exact) return `${leading}${exact}${trailing}`;
  if (core.length > 1200) return value;
  let next = core;
  for (const [from, to] of orderedTranslations) {
    if (next.includes(from)) next = next.split(from).join(to);
  }
  return `${leading}${next}${trailing}`;
}

function shouldSkipTextElement(element: Element): boolean {
  return Boolean(element.closest("script,style,noscript,textarea,canvas,[data-no-translate]"));
}

function shouldSkipAttributeElement(element: Element): boolean {
  return Boolean(element.closest("script,style,noscript,svg,canvas,[data-no-translate]"));
}

function applyTextNode(node: Text, language: AppLanguage) {
  const parent = node.parentElement;
  if (!parent || shouldSkipTextElement(parent)) return;
  const current = node.nodeValue ?? "";
  let original = textOriginals.get(node);
  if (original === undefined) {
    original = current;
    textOriginals.set(node, original);
  } else if (language !== "ps") {
    const translatedOriginal = translateValue(original, language);
    if (current !== original && current !== translatedOriginal) {
      original = current;
      textOriginals.set(node, original);
    }
  }
  const translated = translateValue(original, language);
  if (node.nodeValue !== translated) node.nodeValue = translated;
}

function applyAttributes(element: Element, language: AppLanguage) {
  if (shouldSkipAttributeElement(element)) return;
  const attrs = ["placeholder", "title", "aria-label", "alt"];
  for (const attr of attrs) {
    const current = element.getAttribute(attr);
    if (!current) continue;
    const originals = attrOriginals.get(element) ?? {};
    if (!originals[attr]) {
      originals[attr] = current;
      attrOriginals.set(element, originals);
    } else if (language !== "ps") {
      const translatedOriginal = translateValue(originals[attr], language);
      if (current !== originals[attr] && current !== translatedOriginal) {
        originals[attr] = current;
      }
    }
    const translated = translateValue(originals[attr], language);
    if (element.getAttribute(attr) !== translated) element.setAttribute(attr, translated);
  }
}

function walk(root: ParentNode, language: AppLanguage) {
  const walker = document.createTreeWalker(root, NodeFilter.SHOW_TEXT | NodeFilter.SHOW_ELEMENT);
  let node = walker.nextNode();
  while (node) {
    if (node.nodeType === Node.TEXT_NODE) applyTextNode(node as Text, language);
    else if (node.nodeType === Node.ELEMENT_NODE) applyAttributes(node as Element, language);
    node = walker.nextNode();
  }
}

function restore(root: ParentNode) {
  const walker = document.createTreeWalker(root, NodeFilter.SHOW_TEXT | NodeFilter.SHOW_ELEMENT);
  let node = walker.nextNode();
  while (node) {
    if (node.nodeType === Node.TEXT_NODE) {
      const original = textOriginals.get(node as Text);
      if (original !== undefined && node.nodeValue !== original) node.nodeValue = original;
    } else if (node.nodeType === Node.ELEMENT_NODE) {
      const element = node as Element;
      const originals = attrOriginals.get(element);
      if (originals) {
        for (const [attr, value] of Object.entries(originals)) {
          if (element.getAttribute(attr) !== value) element.setAttribute(attr, value);
        }
      }
    }
    node = walker.nextNode();
  }
}

export function applyDocumentLanguage(language: AppLanguage): () => void {
  if (activeObserver) {
    activeObserver.disconnect();
    activeObserver = null;
  }
  const root = document.getElementById("root") ?? document.body;
  if (language === "ps") {
    restore(root);
    return () => undefined;
  }

  const apply = () => walk(root, language);
  requestAnimationFrame(apply);
  activeObserver = new MutationObserver((mutations) => {
    for (const mutation of mutations) {
      if (mutation.type === "characterData") {
        applyTextNode(mutation.target as Text, language);
      } else if (mutation.type === "attributes" && mutation.target instanceof Element) {
        applyAttributes(mutation.target, language);
      } else {
        mutation.addedNodes.forEach((node) => {
          if (node.nodeType === Node.TEXT_NODE) applyTextNode(node as Text, language);
          else if (node.nodeType === Node.ELEMENT_NODE) {
            walk(node as Element, language);
            applyAttributes(node as Element, language);
          }
        });
      }
    }
  });
  activeObserver.observe(root, {
    subtree: true,
    childList: true,
    characterData: true,
    attributes: true,
    attributeFilter: ["placeholder", "title", "aria-label", "alt"],
  });

  return () => {
    activeObserver?.disconnect();
    activeObserver = null;
  };
}
